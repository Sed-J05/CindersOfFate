using System.Collections.Generic;
using System.IO;
using System.Text;
using Shatranj.Level;
using UnityEngine;

namespace Shatranj.EditorTools.Level
{
    /// <summary>Writes Docs/LEVEL_OVERVIEW.md: per-phase room tables and a coarse ASCII layout map (Docs/05 §6).</summary>
    public static class LevelOverviewWriter
    {
        public const string Path = "Docs/LEVEL_OVERVIEW.md";
        private const int CellsPerChar = 4;   // 4 tiles → 1 character / 1 line

        public static void Write(LevelSet set, StringBuilder report)
        {
            var sb = new StringBuilder();
            sb.AppendLine("# LEVEL OVERVIEW (generated by Shatranj/Build Levels — do not edit)");
            sb.AppendLine();
            sb.AppendLine($"Tile = 0.5 u. Map scale: 1 character = {CellsPerChar} tiles horizontally and vertically. Room ids are printed inside their box.");
            sb.AppendLine();

            foreach (LevelManifestPhase phase in set.manifest.phases)
            {
                List<RoomData> rooms = set.RoomsOfPhase(phase);
                sb.AppendLine($"## {phase.id} — {phase.scene} ({phase.theme})");
                sb.AppendLine();
                if (rooms.Count == 0) { sb.AppendLine("_No rooms authored yet._"); sb.AppendLine(); continue; }

                sb.AppendLine("| # | Room | Name | Size (tiles) | Origin | Section | Enemies | Specials |");
                sb.AppendLine("|---|---|---|---|---|---|---|---|");
                foreach (RoomData r in rooms)
                    sb.AppendLine($"| {r.orderIndex} | `{r.id}` | {r.name} | {r.width}×{r.height} | {r.originX},{r.originY} | {r.section} | {r.CountEnemies()} | {Specials(r)} |");
                sb.AppendLine();

                foreach (LevelManifestSection s in phase.sections)
                {
                    int found = 0;
                    foreach (RoomData r in rooms) if (r.section == s.id) found += r.CountEnemies();
                    sb.AppendLine($"- Section **{s.id}**: {found}/{s.expectedEnemies} enemies {(found == s.expectedEnemies ? "✔" : "✘")}");
                }
                sb.AppendLine();
                sb.AppendLine("```");
                sb.Append(AsciiMap(rooms));
                sb.AppendLine("```");
                sb.AppendLine();
            }

            Directory.CreateDirectory(System.IO.Path.GetDirectoryName(Path));
            File.WriteAllText(Path, sb.ToString());
            report?.AppendLine("Wrote " + Path);
        }

        private static string Specials(RoomData r)
        {
            var parts = new List<string>();
            if (r.Contains(Glyphs.PlayerStart)) parts.Add("P");
            if (r.Contains(Glyphs.Bench)) parts.Add("bench");
            if (r.IsBossRoom) parts.Add("boss:" + r.bossId);
            if (r.Contains(Glyphs.Door)) parts.Add("door:" + r.doorFlag);
            if (r.Contains(Glyphs.Orb)) parts.Add("orb");
            if (r.Contains(Glyphs.Spikes)) parts.Add("spikes");
            if (r.Contains(Glyphs.Lava)) parts.Add("lava");
            if (r.Contains(Glyphs.Sign)) parts.Add("signs");
            return string.Join(" ", parts);
        }

        private static string AsciiMap(List<RoomData> rooms)
        {
            int minX = int.MaxValue, minY = int.MaxValue, maxX = int.MinValue, maxY = int.MinValue;
            foreach (RoomData r in rooms)
            {
                minX = Mathf.Min(minX, r.originX); minY = Mathf.Min(minY, r.originY);
                maxX = Mathf.Max(maxX, r.originX + r.width); maxY = Mathf.Max(maxY, r.originY + r.height);
            }
            int w = Mathf.CeilToInt((maxX - minX) / (float)CellsPerChar) + 1;
            int h = Mathf.CeilToInt((maxY - minY) / (float)CellsPerChar) + 1;
            var map = new char[h, w];
            for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) map[y, x] = ' ';

            foreach (RoomData r in rooms)
            {
                int x0 = (r.originX - minX) / CellsPerChar, x1 = (r.originX + r.width - minX) / CellsPerChar;
                int y0 = (r.originY - minY) / CellsPerChar, y1 = (r.originY + r.height - minY) / CellsPerChar;
                for (int y = y0; y <= y1 && y < h; y++)
                    for (int x = x0; x <= x1 && x < w; x++)
                        map[y, x] = (y == y0 || y == y1 || x == x0 || x == x1) ? '#' : (r.IsBossRoom ? '*' : '.');
                string label = r.id;
                int ly = Mathf.Min(h - 1, y0 + 1), lx = x0 + 1;
                for (int i = 0; i < label.Length && lx + i < x1 && lx + i < w; i++) map[ly, lx + i] = label[i];
            }

            var sb = new StringBuilder();
            for (int y = h - 1; y >= 0; y--) // top row = highest y
            {
                var line = new StringBuilder(w);
                for (int x = 0; x < w; x++) line.Append(map[y, x]);
                sb.AppendLine(line.ToString().TrimEnd());
            }
            return sb.ToString();
        }
    }
}
